void fb_put_char(int x, int y, char c, u32 fg, u32 bg)
{
    if (!g_fb) return;
    int ch = (int)(unsigned char)c;
    if (ch < 32 || ch > 126) ch = 32;
    const u8 *glyph = font8x16[ch - 32];
    for (int row = 0; row < 16; row++) {
        u8 bits = glyph[row];
        for (int col = 0; col < 8; col++)
            fb_pixel(x + col, y + row, (bits & (0x80 >> col)) ? fg : bg);
    }
}

void fb_puts(int x, int y, const char *s, u32 fg, u32 bg)
{
    while (*s) {
        fb_put_char(x, y, *s, fg, bg);
        x += 8;
        s++;
    }
}
