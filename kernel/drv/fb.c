/*
 * M9 minimal framebuffer (UEFI GOP).
 * - Init from boot_info (physical address, identity-mapped)
 * - cls / pixel / rect / put_char / puts
 * - Embedded 8x16 VGA bitmap font (ASCII 32-126)
 */
#include "helix/fb.h"
#include "helix/kprintf.h"
#include "helix/string.h"

static volatile u8 *g_fb;
static u32 g_w, g_h, g_pitch, g_bpp;

static inline void w32(volatile void *a, u32 v)
{
    __asm__ volatile("movl %0,(%1)" : : "r"(v), "r"(a) : "memory");
}

#define FB_PIXEL_ADDR(x, y) (g_fb + (u64)(y) * g_pitch + (u64)(x) * (g_bpp / 8))

int fb_init(struct helix_boot_info *info)
{
    if (!info || !info->fb_addr || !info->fb_width || !info->fb_height) {
        kprintf("[fb] no framebuffer\n");
        return -1;
    }
    g_fb    = (volatile u8 *)(uintptr_t)info->fb_addr;
    g_w     = info->fb_width;
    g_h     = info->fb_height;
    g_pitch = info->fb_pitch;
    g_bpp   = info->fb_bpp;
    kprintf("[fb] %ux%u pitch=%u bpp=%u fb=0x%llx\n",
            g_w, g_h, g_pitch, g_bpp, (unsigned long long)info->fb_addr);
    return 0;
}

void fb_cls(u32 color)
{
    if (!g_fb) return;
    for (u32 y = 0; y < g_h; y++)
        for (u32 x = 0; x < g_w; x++)
            w32(FB_PIXEL_ADDR(x, y), color);
}

void fb_pixel(int x, int y, u32 color)
{
    if (x < 0 || y < 0 || (u32)x >= g_w || (u32)y >= g_h) return;
    w32(FB_PIXEL_ADDR(x, y), color);
}

void fb_rect(int x, int y, int w, int h, u32 color)
{
    for (int j = y; j < y + h; j++)
        for (int i = x; i < x + w; i++)
            fb_pixel(i, j, color);
}

